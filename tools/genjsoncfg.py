#!/usr/bin/env python3
"""Generates src/CfgJson.Inc: Pascal code that turns the records of the MK configuration (Struct.MK, MKGlobT.pas) into
JSON objects and back (fpjson), field by field.  Run it again when a record changes:   python3 tools/genjsoncfg.py

  - numbers, booleans, strings (CP437 <-> UTF-8), Char (a one character string, a number when it is not printable)
  - an array is a JSON array; an array of more than 12 records is a sparse object {"6": {...}} that leaves out the
    entries that are empty (their JSON equals that of a record of zeros)
  - fields called Expansion (room for later versions) are not written
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'src')
text = open(os.path.join(src, 'Struct.MK'), encoding='latin-1').read() + '\n' + \
    open(os.path.join(src, 'MKGlobT.pas'), encoding='latin-1').read()
text = re.sub(r'\{[^}]*\}', '', text)                  # comments
text = re.sub(r'\(\*.*?\*\)', '', text, flags=re.S)

consts = {}
for m in re.finditer(r'\b(\w+)\s*=\s*(\$?[0-9A-Fa-f]+)\s*;', text):
    v = m.group(2)
    try:
        consts[m.group(1)] = int(v[1:], 16) if v.startswith('$') else int(v)
    except ValueError:
        pass

records = {}
order = []
for m in re.finditer(r'\bType\s+(\w+)\s*=\s*Record\b(.*?)\bEnd\s*;', text, flags=re.S | re.I):
    name, body = m.group(1), m.group(2)
    fields = []
    for decl in body.split(';'):
        decl = decl.strip()
        if not decl:
            continue
        names, typ = decl.split(':', 1)
        for n in names.split(','):
            fields.append((n.strip(), re.sub(r'\s+', ' ', typ.strip())))
    records[name] = fields
    order.append(name)

# the arrays of records that are not a record type of their own: MsgCfgType, FileCfgType
def num(s):
    s = s.strip()
    if s in consts:
        return consts[s]
    return int(s[1:], 16) if s.startswith('$') else int(s)


def parse_type(t):
    """('scalar', name) | ('string', n) | ('record', name) | ('array', lo, hi, elem)"""
    m = re.match(r'(?i)array\s*\[\s*(\w+)\s*\.\.\s*(\w+)\s*\]\s*of\s+(.*)$', t)
    if m:
        return ('array', num(m.group(1)), num(m.group(2)), parse_type(m.group(3)))
    m = re.match(r'(?i)string\s*\[\s*(\w+)\s*\]$', t)
    if m:
        return ('string', num(m.group(1)))
    if t.lower() in ('byte', 'word', 'longint', 'integer', 'shortint', 'smallint', 'cardinal', 'boolean', 'char'):
        return ('scalar', t.lower())
    if t in records:
        return ('record', t)
    raise SystemExit('unknown type %r' % t)


need = ['BbsCfg', 'MsgAreaType', 'FileAreaType', 'EchoCfgType', 'MailerCfgType']
used = []


def collect(name):
    if name in used:
        return
    for f, t in records[name]:
        ty = parse_type(t)
        while ty[0] == 'array':
            ty = ty[3]
        if ty[0] == 'record':
            collect(ty[1])
    used.append(name)


for n in need:
    collect(n)

SPARSE = 12
USEDKEY = {'MsgAreaType': 'Name', 'FileAreaType': 'Name', 'EchoAreaType': 'AreaTag'}   # an entry with an empty name is not in use
out = []
w = out.append
w('{ Generated by tools/genjsoncfg.py from Struct.MK and MKGlobT.pas: do not edit.  See the header of that script. }')
w('')
cnt = [0]


def var():
    cnt[0] += 1
    return 'i%d' % cnt[0]


def to_json(expr, ty, depth):
    """Pascal expression (TJSONData) for the value expr; statements are emitted before through w()"""
    k = ty[0]
    if k == 'scalar':
        if ty[1] == 'boolean':
            return 'TJSONBoolean.Create(%s)' % expr
        if ty[1] == 'char':
            return 'JsonChar(%s)' % expr
        return 'TJSONInt64Number.Create(%s)' % expr
    if k == 'string':
        return 'TJSONString.Create(PasToJson(ShortOk(%s, %d)))' % (expr, ty[1])
    if k == 'record':
        return 'JsonTo_%s(%s)' % (ty[1], expr)
    raise SystemExit('array inside array is not handled')


def emit_to(name):
    w('Function JsonTo_%s(Var R: %s): TJSONObject;' % (name, name))
    decl = []
    body = []
    for f, t in records[name]:
        if f == 'Expansion':
            continue
        ty = parse_type(t)
        if ty[0] == 'array':
            lo, hi, el = ty[1], ty[2], ty[3]
            v = var()
            decl.append('%s: Integer' % v)
            if el[0] == 'record' and (hi - lo + 1) > SPARSE:
                body.append('  S := TJSONObject.Create;')
                body.append('  For %s := %d To %d Do' % (v, lo, hi))
                body.append('    Begin')
                body.append('    E := JsonTo_%s(R.%s[%s]);' % (el[1], f, v))
                if el[1] in USEDKEY:
                    body.append('    If R.%s[%s].%s <> \'\' Then' % (f, v, USEDKEY[el[1]]))
                else:
                    body.append('    If E.AsJSON <> ZeroJson_%s Then' % el[1])
                body.append("      S.Add(IntToStr(%s), E)" % v)
                body.append('    Else')
                body.append('      E.Free;')
                body.append('    End;')
                body.append("  O.Add('%s', S);" % f)
            else:
                body.append('  A := TJSONArray.Create;')
                body.append('  For %s := %d To %d Do' % (v, lo, hi))
                if el[0] == 'record':
                    body.append('    A.Add(JsonTo_%s(R.%s[%s]));' % (el[1], f, v))
                else:
                    body.append('    A.Add(%s);' % to_json('R.%s[%s]' % (f, v), el, 1))
                body.append("  O.Add('%s', A);" % f)
        elif ty[0] == 'record':
            body.append("  O.Add('%s', JsonTo_%s(R.%s));" % (f, ty[1], f))
        else:
            body.append("  O.Add('%s', %s);" % (f, to_json('R.' + f, ty, 0)))
    bt = '\n'.join(body)
    w('  Var')
    w('    O: TJSONObject;')
    if 'A.' in bt:
        w('    A: TJSONArray;')
    if 'S.' in bt:
        w('    S: TJSONObject;')
    if 'E.' in bt:
        w('    E: TJSONObject;')
    for d in decl:
        w('    ' + d + ';')
    w('')
    w('  Begin')
    w('  O := TJSONObject.Create;')
    for b in body:
        w(b)
    w('  JsonTo_%s := O;' % name)
    w('  End;')
    w('')


def from_value(target, expr, ty):
    k = ty[0]
    if k == 'scalar':
        t = ty[1]
        if t == 'boolean':
            return '%s := JsonBool(%s, %s);' % (target, expr, target)
        if t == 'char':
            return '%s := JsonChar2(%s, %s);' % (target, expr, target)
        rng = {'byte': (0, 255), 'word': (0, 65535), 'longint': (-2147483648, 2147483647), 'integer': (-32768, 32767),
               'shortint': (-128, 127), 'smallint': (-32768, 32767), 'cardinal': (0, 4294967295)}[t]
        return '%s := JsonNum(%s, %s, %d, %d);' % (target, expr, target, rng[0], rng[1])
    if k == 'string':
        return '%s := Copy(JsonStr(%s, %s), 1, %d);' % (target, expr, target, ty[1])
    raise SystemExit('unexpected')


def emit_from(name):
    w('Procedure JsonFrom_%s(O: TJSONObject; Var R: %s);' % (name, name))
    decl = []
    body = []
    for f, t in records[name]:
        if f == 'Expansion':
            continue
        ty = parse_type(t)
        if ty[0] == 'array':
            lo, hi, el = ty[1], ty[2], ty[3]
            v = var()
            decl.append('%s: Integer' % v)
            if el[0] == 'record' and (hi - lo + 1) > SPARSE:
                body.append("  D := O.Find('%s');" % f)
                body.append('  If (D <> Nil) And (D.JSONType = jtObject) Then')
                body.append('    For %s := %d To %d Do' % (v, lo, hi))
                body.append('      Begin')
                body.append("      E := TJSONObject(D).Find(IntToStr(%s));" % v)
                body.append('      If (E <> Nil) And (E.JSONType = jtObject) Then')
                body.append('        JsonFrom_%s(TJSONObject(E), R.%s[%s]);' % (el[1], f, v))
                body.append('      End;')
            else:
                body.append("  D := O.Find('%s');" % f)
                body.append('  If (D <> Nil) And (D.JSONType = jtArray) Then')
                body.append('    For %s := %d To %d Do' % (v, lo, hi))
                body.append('      If %s - %d < TJSONArray(D).Count Then' % (v, lo))
                if el[0] == 'record':
                    body.append('        If TJSONArray(D).Items[%s - %d].JSONType = jtObject Then' % (v, lo))
                    body.append('          JsonFrom_%s(TJSONObject(TJSONArray(D).Items[%s - %d]), R.%s[%s]);' % (el[1], v, lo, f, v))
                else:
                    body.append('        ' + from_value('R.%s[%s]' % (f, v), 'TJSONArray(D).Items[%s - %d]' % (v, lo), el))
        elif ty[0] == 'record':
            body.append("  D := O.Find('%s');" % f)
            body.append('  If (D <> Nil) And (D.JSONType = jtObject) Then')
            body.append('    JsonFrom_%s(TJSONObject(D), R.%s);' % (ty[1], f))
        else:
            body.append("  D := O.Find('%s');" % f)
            body.append('  If D <> Nil Then')
            body.append('    ' + from_value('R.' + f, 'D', ty))
    bt = '\n'.join(body)
    w('  Var')
    w('    D: TJSONData;')
    if 'E :=' in bt:
        w('    E: TJSONData;')
    for d in decl:
        w('    ' + d + ';')
    w('')
    w('  Begin')
    for b in body:
        w(b)
    w('  End;')
    w('')


# forward declarations of the To functions (records contain records)
for n in used:
    w('Function JsonTo_%s(Var R: %s): TJSONObject; Forward;' % (n, n))
w('')
# the JSON of a record of zeros: what an empty entry of a sparse array looks like
for n in used:
    w('Var')
    w('  ZeroJson_%s: String;' % n)
w('')
w('')
for n in used:
    emit_to(n)
for n in used:
    emit_from(n)
for n in used:
    w('Function ZeroOf_%s: String;' % n)
    w('  Var')
    w('    R: %s;' % n)
    w('    J: TJSONObject;')
    w('')
    w('  Begin')
    w('  FillChar(R, SizeOf(R), 0);')
    w('  J := JsonTo_%s(R);' % n)
    w('  ZeroOf_%s := J.AsJSON;' % n)
    w('  J.Free;')
    w('  End;')
    w('')
w('Procedure JsonInitZero;')
w('  Begin')
for n in used:
    w('  ZeroJson_%s := ZeroOf_%s;' % (n, n))
w('  End;')
open(os.path.join(src, 'CfgJson.Inc'), 'w', encoding='latin-1').write('\n'.join(out) + '\n')
print('records:', ', '.join(used))
